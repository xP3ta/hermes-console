import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// CI form of the Gateway retirement gate (U6): production code under `lib`
/// no longer talks to the Gateway REST API. The only matches left are the
/// three liveness lines of the connection without a Dashboard, which carry
/// `// U6b`; the on-device LiteRT/OlliteRT engine is a different server.
final _gatewayCall = RegExp(
  r'v1/(runs|models|capabilities|skills|toolsets)|(?<!/api)/health\b',
);
const _marker = '// U6b';
const _allowedFile = 'lib/core/services/connection_manager.dart';
const _liteRtFiles = {
  'lib/core/data/litert_catalog.dart',
  'lib/core/screens/litert_store_screen.dart',
  'lib/core/services/litert_engine.dart',
};
final _retiredSymbols = RegExp(
  r'GatewayChatClient|probeGateway|ServerCapabilities|startRun|'
  r'streamRunEvents|resolveRunApproval|legacyGatewayLoader|getBackendModels|'
  r'getModelInfoList|runTerminalCancelsApproval|normalizeRunEvent|'
  r'run_event_normalizer|\bModelInfo\b',
);

Iterable<MapEntry<String, List<String>>> _libSources() sync* {
  for (final entity in Directory('lib').listSync(recursive: true)) {
    if (entity is! File || !entity.path.endsWith('.dart')) continue;
    final path = entity.path.replaceAll(r'\', '/');
    // Generated by `flutter gen-l10n`, not tracked.
    if (path.startsWith('lib/l10n/app_localizations')) continue;
    yield MapEntry(path, entity.readAsLinesSync());
  }
}

void main() {
  test('lib has no Gateway REST call but the three marked liveness lines', () {
    final hits = <String>[];
    final marked = <String>[];
    for (final source in _libSources()) {
      if (_liteRtFiles.contains(source.key)) continue;
      for (var i = 0; i < source.value.length; i++) {
        final line = source.value[i];
        final where = '${source.key}:${i + 1}: ${line.trim()}';
        if (_gatewayCall.hasMatch(line)) hits.add(where);
        if (line.contains(_marker)) marked.add(where);
      }
    }
    expect(
      hits,
      everyElement(allOf(startsWith('$_allowedFile:'), endsWith(_marker))),
      reason: 'a Gateway call outside the whitelist',
    );
    expect(hits, hasLength(3), reason: 'the whitelist is exactly 3 lines');
    expect(
      marked,
      hits,
      reason: '`$_marker` is only for the 3 whitelisted lines',
    );
  });

  test('retired Gateway symbols and the Ollama port are gone', () {
    final found = <String>[];
    for (final source in _libSources()) {
      for (var i = 0; i < source.value.length; i++) {
        final line = source.value[i];
        if (_retiredSymbols.hasMatch(line) ||
            (source.key == _allowedFile && line.contains('11434'))) {
          found.add('${source.key}:${i + 1}: ${line.trim()}');
        }
      }
    }
    expect(found, isEmpty);
  });
}
