import 'dart:io';
import 'package:flutter_test/flutter_test.dart';
import 'package:hermes_android/core/services/active_chat_service.dart';

class OfficialResumeServer {
  OfficialResumeServer(this.server) {
    server.listen((request) async {
      paths.add(request.uri.path);
      if (request.uri.path == '/') {
        request.response.write(
          'window.__HERMES_SESSION_TOKEN__="fixture-token";',
        );
      } else if (request.uri.path == '/api/auth/ws-ticket') {
        expect(
          request.headers.value('x-hermes-session-token'),
          'fixture-token',
        );
        request.response.headers.contentType = ContentType.json;
        request.response.write(jsonEncode({'ticket': 'fixture-ticket'}));
      } else if (request.uri.path.endsWith('/sessions/s/messages')) {
        historyReads.add(request.uri);
        request.response.headers.contentType = ContentType.json;
        request.response.write(
          jsonEncode({
            'session_id': 's',
            'messages': List<Map<String, dynamic>>.of(history),
          }),
        );
      } else if (request.uri.path == '/api/ws') {
        expect(request.uri.queryParameters, {'ticket': 'fixture-ticket'});
        final socket = await WebSocketTransformer.upgrade(request);
        sockets.add(socket);
        socket.add(
          jsonEncode({
            'jsonrpc': '2.0',
            'method': 'event',
            'params': {
              'type': 'gateway.ready',
              'payload': {'heartbeat': false},
            },
          }),
        );
        await for (final raw in socket) {
          final frame = jsonDecode(raw as String) as Map<String, dynamic>;
          frames.add(frame);
          final result = switch (frame['method']) {
            'session.resume' => {
              'session_id': 'runtime-fixture',
              'stored_session_id': 's',
              'status': 'idle',
              'running': false,
            },
            'session.active_list' => {'sessions': <Object>[]},
            'gateway.capabilities' => {'per_session_exclusive_submit': true},
            'client.capabilities' => {'server_requests': <Object>[]},
            'session.history' => {
              'messages': List<Map<String, dynamic>>.of(history),
              'count': history.length,
            },
            'prompt.submit' => {'status': 'accepted'},
            _ => <String, dynamic>{},
          };
          if (holdResume &&
              frame['method'] == 'session.resume' &&
              !resumeEntered.isCompleted) {
            resumeEntered.complete();
            await resumeRelease.future;
          }
          if (holdCapability &&
              frame['method'] == 'gateway.capabilities' &&
              !capabilityEntered.isCompleted) {
            capabilityEntered.complete();
            await capabilityRelease.future;
          }
          if (frame['method'] == 'prompt.submit') {
            acceptedReplies++;
            final text = (frame['params'] as Map)['text'] as String;
            history.addAll([
              {'role': 'user', 'content': text, 'row_id': history.length + 1},
              {
                'role': 'assistant',
                'content': 'reply:$text',
                'row_id': history.length + 2,
              },
            ]);
          }
          if (holdAccepted &&
              frame['method'] == 'prompt.submit' &&
              !acceptedEntered.isCompleted) {
            acceptedEntered.complete();
            await acceptedRelease.future;
          }
          // A rejected client can close while background capability replies settle.
          if (socket.readyState == WebSocket.open) {
            try {
              socket.add(
                jsonEncode({
                  'jsonrpc': '2.0',
                  'id': frame['id'],
                  'result': result,
                }),
              );
            } on StateError {
              // Http WebSocket can still report OPEN after its sink closes.
              // A late response cannot revive this client-disposed socket;
              // actual wire counts and positive ACK assertions remain required.
              await socket.close();
              break;
            }
          }
        }
        return;
      } else {
        request.response.statusCode = 404;
      }
      await request.response.close();
    });
  }
  final HttpServer server;
  final paths = <String>[];
  final historyReads = <Uri>[];
  final frames = <Map<String, dynamic>>[];
  // Synthetic durable rows generated by this server after actual acceptance.
  final history = <Map<String, dynamic>>[];
  final sockets = <WebSocket>[];
  int acceptedReplies = 0;
  bool holdResume = false;
  bool holdCapability = false;
  bool holdAccepted = false;
  final acceptedEntered = Completer<void>();
  final acceptedRelease = Completer<void>();
  final capabilityEntered = Completer<void>();
  final capabilityRelease = Completer<void>();
  final resumeEntered = Completer<void>();
  final resumeRelease = Completer<void>();
  static Future<OfficialResumeServer> start() async => OfficialResumeServer(
    await HttpServer.bind(InternetAddress.loopbackIPv4, 0),
  );
  void expectFirstSubmit(ActiveChat chat, String profile, String text) {
    expect(chat.hasDesktopTransport, isTrue);
    expect(chat.sessionProfile, profile);
    expect(chat.connection.id, 'c');
    expect(chat.sessionId, 's');
    final resume = frames.singleWhere((f) => f['method'] == 'session.resume');
    expect(resume['params'], containsPair('session_id', 's'));
    expect(resume['params'], containsPair('profile', profile));
    final submit = frames.singleWhere((f) => f['method'] == 'prompt.submit');
    expect(submit['params'], containsPair('session_id', 'runtime-fixture'));
    expect(submit['params'], containsPair('text', text));
    expect(acceptedReplies, 1);
    expect(paths.where((p) => p.contains('bridge')), isEmpty);
  }

  Future<void> completeTurn(ActiveChat chat, String text) async {
    final completed = chat.changes.firstWhere(
      (event) => event == ActiveChatEvent.done,
    );
    sockets.last.add(
      jsonEncode({
        'jsonrpc': '2.0',
        'method': 'event',
        'params': {
          'type': 'message.complete',
          'session_id': 'runtime-fixture',
          'payload': {'text': 'reply:$text'},
        },
      }),
    );
    await completed.timeout(const Duration(seconds: 5));
  }

  Future<void> close() async {
    for (final socket in sockets) {
      await socket.close();
    }
    await server.close(force: true);
  }
}

