#!/usr/bin/env python3
"""Regenerates lib/core/widgets/link_brand_glyphs.dart.

Hermes Desktop marks each link of its Artifacts view with a Simple Icons
glyph chosen by host (`apps/desktop/src/lib/brand-icon.ts`, `BRAND_ICONS`).
This copies that host table unchanged and the single `d` path of each glyph
from the package Desktop renders them with (`@icons-pack/react-simple-icons`,
which wraps `simple-icons`).

Usage:
  build_link_brand_glyphs.py <hermes-agent checkout> <output .dart>
"""

import json
import pathlib
import re
import sys


def main() -> None:
    root = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])
    table_src = (root / 'apps/desktop/src/lib/brand-icon.ts').read_text()
    package = root / 'node_modules/@icons-pack/react-simple-icons'
    version = json.loads((package / 'package.json').read_text())
    simple = version['devDependencies'].get('simple-icons') or version[
        'dependencies'
    ]['simple-icons']
    hosts = re.findall(r"^\s*'([^']+)': Si(\w+),", table_src, re.M)
    if not hosts:
        sys.exit('no BRAND_ICONS entries found')
    slugs = sorted({name.lower() for _, name in hosts})
    paths = {}
    for host, name in hosts:
        module = (package / 'icons' / f'Si{name}.mjs').read_text()
        found = re.findall(r'"path", \{ d: "([^"]+)"', module)
        if len(found) != 1:
            sys.exit(f'Si{name}: expected one path, found {len(found)}')
        paths[name.lower()] = found[0]

    lines = [
        '// GENERATED by tool/brand_icons/build_link_brand_glyphs.py. Do not',
        '// edit by hand.',
        '//',
        f'// Brand glyph path data from Simple Icons {simple}',
        '// (https://github.com/simple-icons/simple-icons), released under',
        '// CC0-1.0, as packaged by @icons-pack/react-simple-icons '
        f"{version['version']}, the",
        '// package Hermes Desktop draws them with. Each entry is the single `d`',
        '// attribute of the glyph (24x24 viewBox), copied unchanged. Colours are',
        '// NOT taken: the app tints every glyph with its own theme tokens. See',
        '// ASSET_PROVENANCE.md. Brand names and marks remain trademarks of their',
        '// owners; they only tell which site a link of the conversation opens.',
        '',
        "/// Hermes Desktop's `BRAND_ICONS` (`lib/brand-icon.ts`): registrable",
        '/// host to Simple Icons slug, in its order.',
        'const Map<String, String> linkBrandHostSlugs = {',
    ]
    for host, name in hosts:
        lines.append(f"  '{host}': '{name.lower()}',")
    lines += [
        '};',
        '',
        '/// SVG path data per Simple Icons slug (viewBox 0 0 24 24).',
        'const Map<String, String> linkBrandGlyphPaths = {',
    ]
    for slug in slugs:
        # dart format: an entry that fits in 80 columns stays on one line.
        entry = f"  '{slug}': '{paths[slug]}',"
        if len(entry) <= 80:
            lines.append(entry)
        else:
            lines.append(f"  '{slug}':")
            lines.append(f"      '{paths[slug]}',")
    lines.append('};')
    out.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
